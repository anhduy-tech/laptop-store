ALTER TABLE attendance ADD opening_cash NUMBER(15,2) DEFAULT 0 NOT NULL;

CREATE TABLE shift_handover (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  assignment_id NUMBER(19) NOT NULL,
  receiver_id NUMBER(19),
  expected_cash NUMBER(15,2) NOT NULL,
  handed_cash NUMBER(15,2) NOT NULL,
  cash_variance NUMBER(15,2) NOT NULL,
  received_cash NUMBER(15,2),
  receive_variance NUMBER(15,2),
  note VARCHAR2(255 CHAR),
  receiver_note VARCHAR2(255 CHAR),
  status VARCHAR2(10 CHAR) NOT NULL,
  confirmed_by NUMBER(19),
  confirmed_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE,
  created_by NUMBER(19),
  updated_by NUMBER(19),
  CONSTRAINT pk_shift_handover PRIMARY KEY (id),
  CONSTRAINT uq_shift_handover_assignment UNIQUE (assignment_id),
  CONSTRAINT ck_shift_handover_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CLOSED'))
);

ALTER TABLE shift_handover ADD CONSTRAINT fk_shift_handover_assignment
  FOREIGN KEY (assignment_id) REFERENCES shift_assignment (id);
ALTER TABLE shift_handover ADD CONSTRAINT fk_shift_handover_receiver
  FOREIGN KEY (receiver_id) REFERENCES app_user (id);
ALTER TABLE shift_handover ADD CONSTRAINT fk_shift_handover_confirmed_by
  FOREIGN KEY (confirmed_by) REFERENCES app_user (id);

CREATE INDEX ix_shift_handover_receiver ON shift_handover (receiver_id, status);
